function createItems(prefix: string, names: string[], images = [sprite, sprite, sprite, hero, sprite, hero]): Reference[] {
  const positions = ["left top", "right top", "left bottom", "right bottom", "left top", "right top"];
  return names.map((title, index) => ({
    id: `${prefix}-${index + 1}`,
    title,
    image: images[index],
    position: positions[index],
    prompt: prompts[prefix][index],
    images: [{
      url: images[index] === sprite ? `/images/references/model-${index % 4 + 1}.png` : images[index],
      name: title,
    }],
    tags: index === 0 ? ["Популярно", "Тренд"] : index === 1 ? ["Новинка"] : [],
  }));
}

